number = 0

while number <= 10:
    number = number + 1
    if number == 5:
        break
    print(number)

# тут срабатывает услоиве(if), когда намбер = 5 это будет True дальше срабатывает подусловие break
# break выкидывает нас из цила и дальше циклы до 10 НЕ будут срабатывать
# print(number) должен быть подусловие while тогда он запишет все циклы, а если он будет как отдельный код то
# запишет только результат, который дал нам break
